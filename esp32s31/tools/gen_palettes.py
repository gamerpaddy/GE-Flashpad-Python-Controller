#!/usr/bin/env python
"""Dump the 9 display palettes as exact 256x3 RGB tables into www/palettes.js.

Each table is cv2.applyColorMap(arange(256), COLORMAP_X)[0][:, ::-1]  (BGR -> RGB), exactly what
flashpad_capture_gui.render_rgb does; Grayscale is the identity. The tables are embedded as base64 (768 bytes each).
Needs cv2 + numpy (build-time only; the browser never needs them).
"""
import base64
import os
import sys

import cv2
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "www", "palettes.js")

# UI order == flashpad_capture_gui.PALETTES order
PALETTES = [
    ("Grayscale", None),
    ("Bone", cv2.COLORMAP_BONE),
    ("Hot", cv2.COLORMAP_HOT),
    ("Inferno", cv2.COLORMAP_INFERNO),
    ("Magma", cv2.COLORMAP_MAGMA),
    ("Plasma", cv2.COLORMAP_PLASMA),
    ("Viridis", cv2.COLORMAP_VIRIDIS),
    ("Turbo", cv2.COLORMAP_TURBO),
    ("Jet", cv2.COLORMAP_JET),
]


def table(cmap):
    ramp = np.arange(256, dtype=np.uint8)
    if cmap is None:
        return np.stack([ramp, ramp, ramp], axis=1)
    return np.ascontiguousarray(cv2.applyColorMap(ramp.reshape(1, 256), cmap)[0][:, ::-1])


def main():
    out = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else OUT)
    lines = []
    for name, cmap in PALETTES:
        t = table(cmap)
        assert t.shape == (256, 3) and t.dtype == np.uint8
        lines.append('    %s: "%s"' % (name, base64.b64encode(t.tobytes()).decode("ascii")))
    js = """/* GENERATED by tools/gen_palettes.py (cv2 %s) - do not edit.
 * 9 exact 256x3 RGB lookup tables, identical to cv2.applyColorMap(...)[:, ::-1] used by flashpad_capture_gui.py. */
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.Palettes = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';
  var B64 = {
%s
  };
  var NAMES = [%s];
  var cache = {};
  function decode(s) {
    var bin = atob(s), n = bin.length, u = new Uint8Array(n);
    for (var i = 0; i < n; i++) u[i] = bin.charCodeAt(i);
    return u;
  }
  /** Uint8Array(768): r0,g0,b0, r1,g1,b1, ... for u8 value 0..255 */
  function get(name) {
    if (!B64.hasOwnProperty(name)) name = 'Grayscale';
    return cache[name] || (cache[name] = decode(B64[name]));
  }
  return { names: NAMES, get: get };
});
""" % (cv2.__version__, ",\n".join(lines), ", ".join('"%s"' % n for n, _ in PALETTES))
    with open(out, "w", newline="\n") as f:
        f.write(js)
    print("wrote", out, len(js), "bytes")


if __name__ == "__main__":
    main()
